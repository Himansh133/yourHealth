"""One-off reference loader (plan 9.2, 9.3): fetch one openFDA label per ingredient, then check every
curated medicine -> lab effect against the label text it cites.

    cd backend && .venv/bin/python -m app.refdata.fetch_openfda

Only generic drug names are sent to openFDA, never patient data. Output is committed to the repo:
  refdata/seed/drug_labels.jsonl          label sections + provenance
  refdata/EFFECTS_VERIFICATION.md         which effect rows the label text supports
"""
import csv
import json
import time
import urllib.parse
import urllib.request
from datetime import date

from app.core.config import settings
from app.refdata.labels import first_sentence, pick_label, verify_effect

API = "https://api.fda.gov/drug/label.json"
KEEP = ["indications_and_usage", "dosage_and_administration", "warnings_and_cautions", "warnings", "precautions",
        "adverse_reactions", "laboratory_tests", "boxed_warning", "drug_interactions"]
SEED = settings.refdata_dir


def fetch(us_name: str) -> tuple[dict | None, str]:
    query = f'openfda.generic_name.exact:"{us_name}"'
    url = f"{API}?{urllib.parse.urlencode({'search': query, 'limit': 50})}"
    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            results = json.load(resp)["results"]
    except urllib.error.HTTPError as e:
        if e.code == 404:  # openFDA's "no matches"
            return None, url
        raise
    return pick_label(results), url


def main() -> None:
    ingredients = list(csv.DictReader(open(SEED / "drug_ingredients.csv", encoding="utf-8")))
    labels = {}
    with open(SEED / "drug_labels.jsonl", "w", encoding="utf-8") as out:
        for ing in ingredients:
            if not ing["us_label_name"]:
                print(f"  {ing['name']}: no US label name (not sold in the US), skipped")
                continue
            label, api_url = fetch(ing["us_label_name"])
            time.sleep(0.3)  # stay well under openFDA's 240 requests/minute without a key
            if label is None:
                print(f"  {ing['name']}: no single-ingredient label found")
                continue
            labels[ing["name"]] = label
            record = {
                "ingredient": ing["name"],
                "set_id": label["set_id"],
                "effective_time": label.get("effective_time"),
                "product_type": label["openfda"].get("product_type", [None])[0],
                "route": label["openfda"].get("route", []),
                "rxcui": label["openfda"].get("rxcui", []),
                "source_url": f"https://dailymed.nlm.nih.gov/dailymed/drugInfo.cfm?setid={label['set_id']}",
                "api_url": api_url,
                "fetched_on": date.today().isoformat(),
                "used_for": first_sentence(" ".join(label.get("indications_and_usage", []))),
                "sections": {k: label[k] for k in KEEP if k in label},
            }
            out.write(json.dumps(record, ensure_ascii=False) + "\n")
            print(f"  {ing['name']}: {record['product_type']} label {label['set_id']} ({record['effective_time']})")

    rows = list(csv.DictReader(open(SEED / "drug_lab_effects.csv", encoding="utf-8")))
    lines = [
        "# Medicine -> lab effect verification",
        "",
        f"Generated by `app.refdata.fetch_openfda` on {date.today().isoformat()}. A row is **supported** when one of",
        "its evidence phrases appears in the openFDA label section it cites. Supported is not the same as reviewed:",
        "a team member and the faculty mentor still read each row against the label (plan 9.4).",
        "",
        "| Ingredient | LOINC | Direction | Type | Section | Evidence | Result |",
        "|---|---|---|---|---|---|---|",
    ]
    ok = 0
    for r in rows:
        label = labels.get(r["ingredient"])
        supported = bool(label) and verify_effect(label, r["source_section"], r["evidence"])
        ok += supported
        result = "supported" if supported else ("**no label**" if not label else "**NOT FOUND in section**")
        lines.append(f"| {r['ingredient']} | {r['loinc_code']} | {r['direction']} | {r['effect_type']} | "
                     f"{r['source_section']} | {r['evidence']} | {result} |")
    lines += ["", f"**{ok} of {len(rows)} rows supported by label text.**", ""]
    (SEED.parent / "EFFECTS_VERIFICATION.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\n{ok}/{len(rows)} effect rows supported by the cited label section")


if __name__ == "__main__":
    main()
